    private final int code;

    @Getter
    private final ErrorCodeCategory category;

    ErrorCode(int code, ErrorCodeCategory category) {
        if (!category.contains(code)) {
            throw new IllegalArgumentException("Error code %s is outside category %s range".formatted(code, category));
        }
        this.code = code;
        this.category = category;
    }
